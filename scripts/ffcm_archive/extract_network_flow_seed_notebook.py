#!/usr/bin/env python3
"""Extract code and markdown from the recovered network-flow seed notebook."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def cell_source(cell: dict) -> str:
    source = cell.get("source", "")
    if isinstance(source, list):
        return "".join(source)
    return str(source)


def first_markdown_heading(markdown: str) -> str:
    for line in markdown.splitlines():
        line = line.strip()
        if line.startswith("#"):
            return line.lstrip("#").strip()
    return ""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--notebook", type=Path, default=Path("tmp/gist-network-flow/phase2_ua06451.ipynb"))
    parser.add_argument("--out-dir", type=Path, default=Path("metadata/ffcm-archive/network-flow-seed"))
    parser.add_argument(
        "--source-url",
        default="https://gist.github.com/gparadis/bcc357dbeaab2c8d247776424c51c25a",
    )
    args = parser.parse_args()

    nb = json.loads(args.notebook.read_text(encoding="utf-8"))
    cells = nb.get("cells", [])
    args.out_dir.mkdir(parents=True, exist_ok=True)

    code_chunks: list[str] = [
        "# Extracted code from phase2_ua06451.ipynb",
        f"# Source gist: {args.source_url}",
        "# Generated by scripts/ffcm_archive/extract_network_flow_seed_notebook.py",
        "",
    ]
    markdown_chunks: list[str] = [
        "# Extracted Markdown From phase2_ua06451.ipynb",
        "",
        f"Source gist: `{args.source_url}`",
        "",
        "This file preserves notebook markdown for semantic recovery. It excludes code-cell outputs.",
        "",
    ]
    rows: list[dict[str, str]] = []

    markdown_heading = ""
    code_index = 0
    markdown_index = 0
    for idx, cell in enumerate(cells, start=1):
        ctype = cell.get("cell_type", "")
        source = cell_source(cell)
        if ctype == "markdown":
            markdown_index += 1
            heading = first_markdown_heading(source)
            if heading:
                markdown_heading = heading
            markdown_chunks.extend([f"<!-- cell {idx} -->", "", source.rstrip(), ""])
        elif ctype == "code":
            code_index += 1
            code_chunks.extend([f"# %% notebook cell {idx}", source.rstrip(), ""])
        rows.append(
            {
                "cell_index": str(idx),
                "cell_type": ctype,
                "source_chars": str(len(source)),
                "markdown_context": markdown_heading,
                "code_cell_index": str(code_index) if ctype == "code" else "",
                "markdown_cell_index": str(markdown_index) if ctype == "markdown" else "",
                "first_line": source.strip().splitlines()[0][:200] if source.strip() else "",
            }
        )

    (args.out_dir / "phase2_ua06451_extracted_code.py.txt").write_text("\n".join(code_chunks), encoding="utf-8")
    (args.out_dir / "phase2_ua06451_extracted_markdown.md").write_text("\n".join(markdown_chunks), encoding="utf-8")
    with (args.out_dir / "phase2_ua06451_cell_index.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "cell_index",
                "cell_type",
                "source_chars",
                "markdown_context",
                "code_cell_index",
                "markdown_cell_index",
                "first_line",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)


if __name__ == "__main__":
    main()
