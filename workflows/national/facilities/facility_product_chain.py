"""Build the national facility-level product/residue chain v1.

This builder joins two upstream screening artifacts:

* ``national_product_chain_v1`` supplies provincial class feedstock and the
  product/residue quantities generated by each class.
* ``national_facility_assignment_v2`` supplies the ``published_plus_proxy``
  facility set and the assigned volume used as the allocation weight.

The join is deliberately class-safe.  A SAW facility can only receive SAW
feedstock, a PULP facility only PULP feedstock, and so on.  Within a province
and class, feedstock is allocated in proportion to the facility's assigned
volume in assignment v2.  When a province has no assigned facility of the
required class, the class stream is routed to the national set of assigned
facilities of that class; that fallback is explicit in ``allocation_scope``
rather than hidden by mixing classes.

Products and process residue are calculated with the effective province/class
conversion ratios implied by the product-chain artifact.  Harvest residue is a
provincial estimate and is kept separate from facility process residue.

Fail-closed rules
-----------------
* No NaN, infinity, or negative quantity is written.
* Every facility allocation is class-matched.
* Facility class feedstock must sum to product-chain province class feedstock.
* Facility products and process residue must sum to product-chain totals.
* Any unexpected ``D`` in the parent or ``data`` repository status halts the
  builder.  The builder never deletes files.

Output labels
-------------
Every row is ``model_estimate=true``, ``observed=false``,
``policy_grade=false``, and ``facility_assignment=true``.  The artifact is a
screening integration, not an operating, policy, AAC, or investment claim.
"""

