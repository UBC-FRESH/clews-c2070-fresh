def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_csv(
    path: Path, required: Sequence[str], label: str
) -> pd.DataFrame:
    if not path.is_file():
        raise FacilityProductChainError(f"{label} does not exist: {path}")
    frame = pd.read_csv(path, keep_default_na=False, dtype=str)
    missing = [column for column in required if column not in frame.columns]
    if missing:
        raise FacilityProductChainError(
            f"{label} is missing columns {missing}: {path}"
        )
    if frame.empty:
        raise FacilityProductChainError(f"{label} is empty: {path}")
    return frame


def _finite_nonnegative(value: Any, label: str) -> float:
    try:
        parsed = float(value)
    except (TypeError, ValueError) as exc:
        raise FacilityProductChainError(
            f"{label} is not numeric: {value!r}"
        ) from exc
    if not math.isfinite(parsed):
        raise FacilityProductChainError(f"{label} is not finite: {parsed!r}")
    if parsed < 0.0:
        raise FacilityProductChainError(f"{label} is negative: {parsed!r}")
    return parsed


def _parse_bool(value: Any, label: str) -> bool:
    text = str(value).strip().lower()
    if text in {"true", "1", "yes"}:
        return True
    if text in {"false", "0", "no", ""}:
        return False
    raise FacilityProductChainError(f"{label} is not a boolean: {value!r}")


def _require_close(left: float, right: float, label: str) -> None:
    scale = max(abs(left), abs(right), 1.0)
    if abs(left - right) > REL_TOL * scale:
        raise FacilityProductChainError(
            f"{label} mismatch: {left!r} != {right!r} "
            f"(relative {abs(left - right) / scale:.3e})"
        )


def _require_between(value: float, low: float, high: float, label: str) -> None:
    if not math.isfinite(value) or value < low or value > high:
        raise FacilityProductChainError(
            f"{label} is outside [{low}, {high}]: {value!r}"
        )


def _git_deletions(repository: Path) -> list[str]:
    result = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=repository,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise FacilityProductChainError(
            f"cannot inspect git status in {repository}: {result.stderr.strip()}"
        )
    deletions: list[str] = []
    for line in result.stdout.splitlines():
        if len(line) < 2:
            continue
        if line[0] == "D" or line[1] == "D":
            deletions.append(line)
    return deletions


def assert_no_unexpected_deletions() -> None:
    """Fail closed on any ``D`` in the parent or data repository status."""
    incidents: list[str] = []
    for repository in (REPO_ROOT, DATA_ROOT):
        for line in _git_deletions(repository):
            incidents.append(f"{repository.name or repository}: {line}")
    if incidents:
        raise FacilityProductChainError(
            "unexpected deletion status detected; halting: "
            + " | ".join(incidents)
        )


def _parse_product_chain() -> tuple[dict[str, ProvinceChain], dict[str, Any]]:
    path = PRODUCT_CHAIN_DIR / "product_chain_by_province.csv"
    required = [
        "province",
        "province_name",
        "harvest_m3",
        "primary_feedstock_m3",
        "residue_feedstock_m3",
        "total_feedstock_m3",
        *CLASS_FEEDSTOCK_COLUMN.values(),
        *CLASS_PRODUCT_COLUMN.values(),
        *CLASS_RESIDUE_COLUMN.values(),
        "harvest_residue_gross_m3",
        "harvest_residue_gross_odt",
        "harvest_residue_recoverable_m3",
        "harvest_residue_recoverable_odt",
        "harvest_residue_unrecovered_m3",
        "harvest_residue_unrecovered_odt",
        "rsyc_base_recoverable_odt",
        "model_recoverable_odt_base",
        "rsyc_ratio",
        "rsyc_status",
        "coefficient_tier",
        "model_estimate",
        "observed",
        "policy_grade",
        "facility_assignment",
    ]
    frame = _read_csv(path, required, "product-chain province table")
    summary_path = PRODUCT_CHAIN_DIR / "summary.json"
    if not summary_path.is_file():
        raise FacilityProductChainError(
            f"product-chain summary is missing: {summary_path}"
        )
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("artifact") != "national_product_chain_v1":
        raise FacilityProductChainError(
            f"unexpected product-chain artifact: {summary.get('artifact')!r}"
        )
    if summary.get("model_estimate") is not True:
        raise FacilityProductChainError("product chain is not labelled model_estimate")
    if summary.get("observed") is not False:
        raise FacilityProductChainError("product chain is not labelled observed=false")
    if summary.get("policy_grade") is not False:
        raise FacilityProductChainError("product chain is not labelled policy_grade=false")
    if summary.get("facility_assignment") is not False:
        raise FacilityProductChainError(
            "product chain unexpectedly contains a facility assignment"
        )

    frame["province"] = frame["province"].astype(str).str.strip().str.upper()
    provinces = set(frame["province"])
    if provinces != set(PROVINCES):
        missing = set(PROVINCES) - provinces
        extra = provinces - set(PROVINCES)
        raise FacilityProductChainError(
            f"product-chain province set mismatch; missing={sorted(missing)}, "
            f"extra={sorted(extra)}"
        )
    if frame["province"].duplicated().any():
        raise FacilityProductChainError("product-chain province table has duplicates")

    chains: dict[str, ProvinceChain] = {}
    for _, record in frame.iterrows():
        province = str(record["province"]).upper()
        harvest = _finite_nonnegative(
            record["harvest_m3"], f"{province} harvest_m3"
        )
        primary = _finite_nonnegative(
            record["primary_feedstock_m3"], f"{province} primary_feedstock_m3"
        )
        residue_feedstock = _finite_nonnegative(
            record["residue_feedstock_m3"], f"{province} residue_feedstock_m3"
        )
        total_feedstock = _finite_nonnegative(
            record["total_feedstock_m3"], f"{province} total_feedstock_m3"
        )
        _require_close(
            primary + residue_feedstock,
            total_feedstock,
            f"{province} primary plus residue feedstock",
        )
        class_feedstock = {
            facility_class: _finite_nonnegative(
                record[CLASS_FEEDSTOCK_COLUMN[facility_class]],
                f"{province}/{facility_class} feedstock",
            )
            for facility_class in CLASS_ORDER
        }
        _require_close(
            math.fsum(class_feedstock.values()),
            total_feedstock,
            f"{province} class feedstock conservation",
        )
        _require_close(
            primary,
            harvest,
            f"{province} primary feedstock versus harvest",
        )
        class_product = {
            facility_class: _finite_nonnegative(
                record[CLASS_PRODUCT_COLUMN[facility_class]],
                f"{province}/{facility_class} product",
            )
            for facility_class in CLASS_ORDER
        }
        class_residue_odt = {
            facility_class: _finite_nonnegative(
                record[CLASS_RESIDUE_COLUMN[facility_class]],
                f"{province}/{facility_class} residue",
            )
            for facility_class in CLASS_ORDER
        }
        model_estimate = _parse_bool(
            record["model_estimate"], f"{province} model_estimate"
        )
        observed = _parse_bool(record["observed"], f"{province} observed")
        policy_grade = _parse_bool(
            record["policy_grade"], f"{province} policy_grade"
        )
        facility_assignment = _parse_bool(
            record["facility_assignment"], f"{province} facility_assignment"
        )
        if not model_estimate or observed or policy_grade or facility_assignment:
            raise FacilityProductChainError(
                f"{province} product-chain labels are not screening labels"
            )
        coefficient_tier = str(record["coefficient_tier"]).strip()
        if coefficient_tier not in {
            "bc_anchor_species_group",
            "donor_coefficient",
        }:
            raise FacilityProductChainError(
                f"{province} unexpected coefficient tier {coefficient_tier!r}"
            )
        chains[province] = ProvinceChain(
            province=province,
            province_name=str(record["province_name"]).strip(),
            harvest_m3=harvest,
            primary_feedstock_m3=primary,
            residue_feedstock_m3=residue_feedstock,
            total_feedstock_m3=total_feedstock,
            class_feedstock_m3=class_feedstock,
            class_product=class_product,
            class_residue_odt=class_residue_odt,
            harvest_residue_gross_m3=_finite_nonnegative(
                record["harvest_residue_gross_m3"],
                f"{province} harvest_residue_gross_m3",
            ),
            harvest_residue_gross_odt=_finite_nonnegative(
                record["harvest_residue_gross_odt"],
                f"{province} harvest_residue_gross_odt",
            ),
            harvest_residue_recoverable_m3=_finite_nonnegative(
                record["harvest_residue_recoverable_m3"],
                f"{province} harvest_residue_recoverable_m3",
            ),
            harvest_residue_recoverable_odt=_finite_nonnegative(
                record["harvest_residue_recoverable_odt"],
                f"{province} harvest_residue_recoverable_odt",
            ),
            harvest_residue_unrecovered_m3=_finite_nonnegative(
                record["harvest_residue_unrecovered_m3"],
                f"{province} harvest_residue_unrecovered_m3",
            ),
            harvest_residue_unrecovered_odt=_finite_nonnegative(
                record["harvest_residue_unrecovered_odt"],
                f"{province} harvest_residue_unrecovered_odt",
            ),
            rsyc_base_recoverable_odt=_finite_nonnegative(
                record["rsyc_base_recoverable_odt"],
                f"{province} rsyc_base_recoverable_odt",
            ),
            model_recoverable_odt_base=_finite_nonnegative(
                record["model_recoverable_odt_base"],
                f"{province} model_recoverable_odt_base",
            ),
            rsyc_ratio=_finite_nonnegative(
                record["rsyc_ratio"], f"{province} rsyc_ratio"
            ),
            rsyc_status=str(record["rsyc_status"]).strip(),
            coefficient_tier=coefficient_tier,
        )

    national_harvest = math.fsum(
        chain.harvest_m3 for chain in chains.values()
    )
    _require_close(
        national_harvest,
        float(summary["harvest_total_m3"]),
        "product-chain harvest total",
    )
    return chains, summary


def _parse_assignment() -> tuple[list[AssignmentLink], dict[str, Any]]:
    path = ASSIGNMENT_DIR / "facility_assignment.csv"
    required = [
        "scenario",
        "province",
        "facility_id",
        "facility_name",
        "facility_class",
        "facility_province",
        "cross_border",
        "capacity_status",
        "capacity_m3_y",
        "assigned_m3",
        "utilization",
        "evidence_label",
        "observed",
        "policy_grade",
    ]
    frame = _read_csv(path, required, "facility assignment")
    frame = frame[frame["scenario"].astype(str).str.strip() == SCENARIO].copy()
    if frame.empty:
        raise FacilityProductChainError(
            f"assignment has no rows for scenario {SCENARIO!r}"
        )
    summary_path = ASSIGNMENT_DIR / "summary.json"
    if not summary_path.is_file():
        raise FacilityProductChainError(
            f"assignment summary is missing: {summary_path}"
        )
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("artifact") != "national_facility_assignment_v2":
        raise FacilityProductChainError(
            f"unexpected assignment artifact: {summary.get('artifact')!r}"
        )
    if SCENARIO not in summary.get("scenarios", {}):
        raise FacilityProductChainError(
            f"assignment summary lacks scenario {SCENARIO!r}"
        )

    links: list[AssignmentLink] = []
    seen_origins: set[tuple[str, str]] = set()
    facility_meta: dict[str, tuple[str, str]] = {}
    for position, record in frame.iterrows():
        assignment_province = str(record["province"]).strip().upper()
        if assignment_province not in PROVINCES:
            raise FacilityProductChainError(
                f"assignment row {position}: unexpected province "
                f"{assignment_province!r}"
            )
        facility_class = str(record["facility_class"]).strip().upper()
        if facility_class not in CLASS_ORDER:
            raise FacilityProductChainError(
                f"assignment row {position}: unexpected facility_class "
                f"{facility_class!r}"
            )
        facility_province = str(record["facility_province"]).strip().upper()
        if facility_province not in PROVINCES:
            raise FacilityProductChainError(
                f"assignment row {position}: unexpected facility province "
                f"{facility_province!r}"
            )
        facility_id = str(record["facility_id"]).strip()
        if not facility_id:
            raise FacilityProductChainError(
                f"assignment row {position}: empty facility_id"
            )
        origin_key = (assignment_province, facility_id)
        if origin_key in seen_origins:
            raise FacilityProductChainError(
                f"duplicate assignment row for {origin_key}"
            )
        seen_origins.add(origin_key)
        expected_meta = (facility_class, facility_province)
        if facility_id in facility_meta and facility_meta[facility_id] != expected_meta:
            raise FacilityProductChainError(
                f"{facility_id}: facility class/province changes across rows"
            )
        facility_meta[facility_id] = expected_meta
        assigned = _finite_nonnegative(
            record["assigned_m3"],
            f"{assignment_province}/{facility_id} assigned_m3",
        )
        if assigned <= 0.0:
            raise FacilityProductChainError(
                f"{assignment_province}/{facility_id}: assignment row has "
                "non-positive assigned volume"
            )
        capacity_status = str(record["capacity_status"]).strip().lower()
        if capacity_status not in {"published", "proxy"}:
            raise FacilityProductChainError(
                f"{facility_id}: unexpected capacity status {capacity_status!r}"
            )
        capacity = _finite_nonnegative(
            record["capacity_m3_y"], f"{facility_id} capacity_m3_y"
        )
        if capacity <= 0.0:
            raise FacilityProductChainError(
                f"{facility_id}: assignment row has non-positive capacity"
            )
        utilization = _finite_nonnegative(
            record["utilization"], f"{facility_id} utilization"
        )
        _require_between(utilization, 0.0, 1.0 + 1e-9, f"{facility_id} utilization")
        if str(record["evidence_label"]).strip() != "model_estimate":
            raise FacilityProductChainError(
                f"{facility_id}: unexpected evidence label"
            )
        if _parse_bool(record["observed"], f"{facility_id} observed"):
            raise FacilityProductChainError(
                f"{facility_id}: assignment row is unexpectedly observed"
            )
        if _parse_bool(record["policy_grade"], f"{facility_id} policy_grade"):
            raise FacilityProductChainError(
                f"{facility_id}: assignment row is unexpectedly policy grade"
            )
        links.append(
            AssignmentLink(
                assignment_province=assignment_province,
                facility_id=facility_id,
                facility_name=str(record["facility_name"]).strip(),
                facility_class=facility_class,
                facility_province=facility_province,
                cross_border=_parse_bool(
                    record["cross_border"], f"{facility_id} cross_border"
                ),
                capacity_status=capacity_status,
                capacity_m3_y=capacity,
                assigned_m3=assigned,
                utilization=utilization,
            )
        )

    assigned_total = math.fsum(link.assigned_m3 for link in links)
    expected = float(summary["scenarios"][SCENARIO]["assigned_m3"])
    _require_close(assigned_total, expected, f"{SCENARIO} assigned total")
    proxy_assigned = math.fsum(
        link.assigned_m3
        for link in links
        if link.capacity_status == "proxy"
    )
    proxy_share = proxy_assigned / assigned_total if assigned_total > 0.0 else 0.0
    expected_proxy = float(
        summary["scenarios"][SCENARIO].get("proxy_share_of_assigned", proxy_share)
    )
    _require_close(proxy_share, expected_proxy, "assignment proxy share")
    return links, summary


def _parse_rsyc_factors() -> dict[str, float]:
    if not RSYC_SUMMARY.is_file():
        raise FacilityProductChainError(f"RSYC summary is missing: {RSYC_SUMMARY}")
    payload = json.loads(RSYC_SUMMARY.read_text(encoding="utf-8"))
    factors: dict[str, float] = {}
    for record in payload.get("province_factors", []):
        province = str(record.get("province", "")).strip().upper()
        if province not in PROVINCES:
            continue
        factors[province] = _finite_nonnegative(
            record["recoverable_odt_per_m3_base"],
            f"RSYC {province} recoverable_odt_per_m3_base",
        )
    if set(factors) != set(PROVINCES):
        missing = set(PROVINCES) - set(factors)
        raise FacilityProductChainError(
            f"RSYC province factors incomplete; missing={sorted(missing)}"
        )
    return factors


def _allocation_pool(
    province: str,
    facility_class: str,
    local_links: Sequence[AssignmentLink],
    national_links: Sequence[AssignmentLink],
) -> tuple[list[AssignmentLink], str]:
    if local_links:
        return list(local_links), "province_assignment"
    if not national_links:
        raise FacilityProductChainError(
            f"no assigned {facility_class} facilities exist nationally for "
            f"{province} class feedstock"
        )
    return list(national_links), "national_class_fallback"


def _allocate(
    chains: Mapping[str, ProvinceChain],
    links: Sequence[AssignmentLink],
) -> list[FacilityAllocation]:
    local_by_origin_class: dict[tuple[str, str], list[AssignmentLink]] = defaultdict(list)
    national_by_class: dict[str, list[AssignmentLink]] = defaultdict(list)
    for link in links:
        local_by_origin_class[
            (link.assignment_province, link.facility_class)
        ].append(link)
        national_by_class[link.facility_class].append(link)

    allocations: list[FacilityAllocation] = []
    for province in PROVINCES:
        chain = chains[province]
        for facility_class in CLASS_ORDER:
            feedstock = chain.class_feedstock_m3[facility_class]
            if feedstock <= 0.0:
                continue
            pool, scope = _allocation_pool(
                province,
                facility_class,
                local_by_origin_class.get((province, facility_class), []),
                national_by_class.get(facility_class, []),
            )
            total_weight = math.fsum(link.assigned_m3 for link in pool)
            if total_weight <= 0.0:
                raise FacilityProductChainError(
                    f"{province}/{facility_class}: allocation weight is zero"
                )
            product_reference = chain.class_product[facility_class]
            residue_reference = chain.class_residue_odt[facility_class]
            product_per_m3 = product_reference / feedstock
            residue_odt_per_m3 = residue_reference / feedstock
            group: list[FacilityAllocation] = []
            for link in pool:
                if link.facility_class != facility_class:
                    raise FacilityProductChainError(
                        f"{link.facility_id}: class mixing is not permitted"
                    )
                share = link.assigned_m3 / total_weight
                _require_between(share, 0.0, 1.0, "allocation share")
                volume = feedstock * share
                product = volume * product_per_m3
                residue_odt = volume * residue_odt_per_m3
                if not all(
                    math.isfinite(value) and value >= 0.0
                    for value in (volume, product, residue_odt)
                ):
                    raise FacilityProductChainError(
                        f"{province}/{facility_class}/{link.facility_id}: "
                        "invalid allocation quantity"
                    )
                group.append(
                    FacilityAllocation(
                        origin_province=province,
                        assignment_province=link.assignment_province,
                        facility_id=link.facility_id,
                        facility_name=link.facility_name,
                        facility_class=facility_class,
                        feedstock_class=facility_class,
                        facility_province=link.facility_province,
                        cross_border=link.facility_province != province,
                        allocation_scope=scope,
                        assignment_weight_m3=link.assigned_m3,
                        assignment_share=share,
                        capacity_status=link.capacity_status,
                        capacity_m3_y=link.capacity_m3_y,
                        utilization=link.utilization,
                        feedstock_m3=volume,
                        product_quantity=product,
                        product_unit=CLASS_PRODUCT_UNIT[facility_class],
                        process_residue_odt=residue_odt,
                        process_residue_m3=residue_odt / RESIDUE_DENSITY_ODT_M3,
                        product_per_m3=product_per_m3,
                        residue_odt_per_m3=residue_odt_per_m3,
                        coefficient_tier=chain.coefficient_tier,
                    )
                )
            _require_close(
                math.fsum(item.feedstock_m3 for item in group),
                feedstock,
                f"{province}/{facility_class} facility feedstock conservation",
            )
            _require_close(
                math.fsum(item.product_quantity for item in group),
                product_reference,
                f"{province}/{facility_class} facility product conservation",
            )
            _require_close(
                math.fsum(item.process_residue_odt for item in group),
                residue_reference,
                f"{province}/{facility_class} facility residue conservation",
            )
            allocations.extend(group)
    return allocations


def _facility_totals(
    allocations: Sequence[FacilityAllocation],
) -> tuple[dict[str, float], dict[str, FacilityAllocation]]:
    totals: dict[str, float] = defaultdict(float)
    meta: dict[str, FacilityAllocation] = {}
    for allocation in allocations:
        key = allocation.facility_id
        previous = meta.get(key)
        if previous is None:
            meta[key] = allocation
        elif (
            previous.facility_class != allocation.facility_class
            or previous.facility_province != allocation.facility_province
            or previous.capacity_status != allocation.capacity_status
            or previous.capacity_m3_y != allocation.capacity_m3_y
        ):
            raise FacilityProductChainError(
                f"{key}: facility metadata changes across allocations"
            )
        totals[key] += allocation.feedstock_m3
    return dict(totals), meta


def _rsyc_status(ratio: float, harvest_m3: float) -> str:
    if harvest_m3 <= 0.0:
        return "zero_harvest"
    if ratio < 0.80:
        return "model_below_rsyc"
    if ratio > 1.25:
        return "model_above_rsyc"
    return "within_rsyc_range"


def _build_province_rows(
    chains: Mapping[str, ProvinceChain],
    allocations: Sequence[FacilityAllocation],
    rsyc_factors: Mapping[str, float],
) -> list[dict[str, Any]]:
    by_origin: dict[str, list[FacilityAllocation]] = defaultdict(list)
    for allocation in allocations:
        by_origin[allocation.origin_province].append(allocation)

    rows: list[dict[str, Any]] = []
    for province in PROVINCES:
        chain = chains[province]
        province_allocations = by_origin.get(province, [])
        class_feedstock = {facility_class: 0.0 for facility_class in CLASS_ORDER}
        class_product = {facility_class: 0.0 for facility_class in CLASS_ORDER}
        class_residue = {facility_class: 0.0 for facility_class in CLASS_ORDER}
        for allocation in province_allocations:
            class_feedstock[allocation.facility_class] += allocation.feedstock_m3
            class_product[allocation.facility_class] += allocation.product_quantity
            class_residue[allocation.facility_class] += allocation.process_residue_odt
        facility_feedstock = math.fsum(class_feedstock.values())
        process_residue = math.fsum(class_residue.values())
        process_residue_m3 = process_residue / RESIDUE_DENSITY_ODT_M3
        facility_ids = {allocation.facility_id for allocation in province_allocations}
        local_feedstock = math.fsum(
            allocation.feedstock_m3
            for allocation in province_allocations
            if not allocation.cross_border
        )
        cross_border_feedstock = facility_feedstock - local_feedstock
        proxy_feedstock = math.fsum(
            allocation.feedstock_m3
            for allocation in province_allocations
            if allocation.capacity_status == "proxy"
        )
        fallback_feedstock = math.fsum(
            allocation.feedstock_m3
            for allocation in province_allocations
            if allocation.allocation_scope == "national_class_fallback"
        )
        facility_totals: dict[str, float] = defaultdict(float)
        for allocation in province_allocations:
            facility_totals[allocation.facility_id] += allocation.feedstock_m3
        if facility_feedstock > 0.0:
            shares = [
                value / facility_feedstock for value in facility_totals.values()
            ]
            hhi = math.fsum(share * share for share in shares)
            top1 = max(shares)
            proxy_share = proxy_feedstock / facility_feedstock
            cross_share = cross_border_feedstock / facility_feedstock
            fallback_share = fallback_feedstock / facility_feedstock
        else:
            hhi = 0.0
            top1 = 0.0
            proxy_share = 0.0
            cross_share = 0.0
            fallback_share = 0.0
        class_gaps = {
            facility_class: class_feedstock[facility_class]
            - chain.class_feedstock_m3[facility_class]
            for facility_class in CLASS_ORDER
        }
        product_gaps = {
            facility_class: class_product[facility_class]
            - chain.class_product[facility_class]
            for facility_class in CLASS_ORDER
        }
        residue_gaps = {
            facility_class: class_residue[facility_class]
            - chain.class_residue_odt[facility_class]
            for facility_class in CLASS_ORDER
        }
        max_relative_product_gap = max(
            (
                abs(gap) / max(abs(chain.class_product[facility_class]), 1.0)
                for facility_class, gap in product_gaps.items()
            ),
            default=0.0,
        )
        max_relative_residue_gap = max(
            (
                abs(gap) / max(abs(chain.class_residue_odt[facility_class]), 1.0)
                for facility_class, gap in residue_gaps.items()
            ),
            default=0.0,
        )
        if chain.harvest_m3 > 0.0:
            rsyc_base = chain.harvest_m3 * rsyc_factors[province]
            _require_close(
                rsyc_base,
                chain.rsyc_base_recoverable_odt,
                f"{province} RSYC base reproduction",
            )
            model_recoverable = (
                chain.harvest_residue_gross_odt * RSYC_BASE_RECOVERY
            )
            _require_close(
                model_recoverable,
                chain.model_recoverable_odt_base,
                f"{province} RSYC model reproduction",
            )
            rsyc_ratio = model_recoverable / rsyc_base if rsyc_base > 0.0 else 0.0
        else:
            rsyc_base = 0.0
            model_recoverable = 0.0
            rsyc_ratio = 0.0
        rsyc_status = _rsyc_status(rsyc_ratio, chain.harvest_m3)
        if rsyc_status != chain.rsyc_status:
            raise FacilityProductChainError(
                f"{province}: RSYC status drift; computed {rsyc_status!r}, "
                f"product chain {chain.rsyc_status!r}"
            )
        rows.append(
            {
                "province": province,
                "province_name": chain.province_name,
                "harvest_m3": chain.harvest_m3,
                "primary_feedstock_m3": chain.primary_feedstock_m3,
                "residue_feedstock_m3": chain.residue_feedstock_m3,
                "total_feedstock_m3": chain.total_feedstock_m3,
                **{
                    CLASS_FEEDSTOCK_COLUMN[facility_class]: class_feedstock[
                        facility_class
                    ]
                    for facility_class in CLASS_ORDER
                },
                "facility_feedstock_m3": facility_feedstock,
                "max_abs_class_feedstock_gap_m3": max(
                    (abs(gap) for gap in class_gaps.values()), default=0.0
                ),
                "local_feedstock_m3": local_feedstock,
                "cross_border_feedstock_m3": cross_border_feedstock,
                "cross_border_feedstock_share": cross_share,
                "proxy_feedstock_m3": proxy_feedstock,
                "proxy_feedstock_share": proxy_share,
                "fallback_feedstock_m3": fallback_feedstock,
                "fallback_feedstock_share": fallback_share,
                "facility_count_origin": len(facility_ids),
                "hhi_origin_feedstock": hhi,
                "top1_facility_share_origin": top1,
                **{
                    CLASS_PRODUCT_COLUMN[facility_class]: class_product[
                        facility_class
                    ]
                    for facility_class in CLASS_ORDER
                },
                **{
                    CLASS_RESIDUE_COLUMN[facility_class]: class_residue[
                        facility_class
                    ]
                    for facility_class in CLASS_ORDER
                },
                "process_residue_odt": process_residue,
                "process_residue_m3": process_residue_m3,
                "process_residue_odt_per_m3_feedstock": (
                    process_residue / facility_feedstock
                    if facility_feedstock > 0.0
                    else 0.0
                ),
                "harvest_residue_gross_m3": chain.harvest_residue_gross_m3,
                "harvest_residue_gross_odt": chain.harvest_residue_gross_odt,
                "harvest_residue_recoverable_m3": (
                    chain.harvest_residue_recoverable_m3
                ),
                "harvest_residue_recoverable_odt": (
                    chain.harvest_residue_recoverable_odt
                ),
                "harvest_residue_unrecovered_m3": (
                    chain.harvest_residue_unrecovered_m3
                ),
                "harvest_residue_unrecovered_odt": (
                    chain.harvest_residue_unrecovered_odt
                ),
                "total_residue_gross_odt": (
                    process_residue + chain.harvest_residue_gross_odt
                ),
                "total_residue_recoverable_odt": (
                    process_residue + chain.harvest_residue_recoverable_odt
                ),
                "rsyc_base_recoverable_odt": rsyc_base,
                "model_recoverable_odt_base": model_recoverable,
                "rsyc_ratio": rsyc_ratio,
                "rsyc_status": rsyc_status,
                "max_relative_product_gap": max_relative_product_gap,
                "max_relative_residue_gap": max_relative_residue_gap,
                "coefficient_tier": chain.coefficient_tier,
                "harvest_residue_scope": "province_only",
                "facility_assignment": LABEL_TRUE,
                "model_estimate": LABEL_TRUE,
                "observed": LABEL_FALSE,
                "policy_grade": LABEL_FALSE,
                "notes": (
                    "Facility feedstock/products from class-matched assignment; "
                    "harvest residue is provincial and kept separate."
                ),
            }
        )
    return rows


def _build_class_rows(
    chains: Mapping[str, ProvinceChain],
    allocations: Sequence[FacilityAllocation],
) -> list[dict[str, Any]]:
    by_origin_class: dict[tuple[str, str], list[FacilityAllocation]] = defaultdict(list)
    for allocation in allocations:
        by_origin_class[
            (allocation.origin_province, allocation.facility_class)
        ].append(allocation)
    rows: list[dict[str, Any]] = []
    for province in PROVINCES:
        chain = chains[province]
        for facility_class in CLASS_ORDER:
            reference_feedstock = chain.class_feedstock_m3[facility_class]
            group = by_origin_class.get((province, facility_class), [])
            facility_feedstock = math.fsum(item.feedstock_m3 for item in group)
            product = math.fsum(item.product_quantity for item in group)
            residue = math.fsum(item.process_residue_odt for item in group)
            facility_ids = {item.facility_id for item in group}
            local = math.fsum(
                item.feedstock_m3 for item in group if not item.cross_border
            )
            proxy = math.fsum(
                item.feedstock_m3
                for item in group
                if item.capacity_status == "proxy"
            )
            fallback = math.fsum(
                item.feedstock_m3
                for item in group
                if item.allocation_scope == "national_class_fallback"
            )
            scopes = sorted({item.allocation_scope for item in group})
            rows.append(
                {
                    "province": province,
                    "province_name": chain.province_name,
                    "facility_class": facility_class,
                    "product_unit": CLASS_PRODUCT_UNIT[facility_class],
                    "feedstock_m3": reference_feedstock,
                    "facility_feedstock_m3": facility_feedstock,
                    "feedstock_gap_m3": facility_feedstock - reference_feedstock,
                    "product_quantity": product,
                    "reference_product_quantity": chain.class_product[facility_class],
                    "product_gap": product - chain.class_product[facility_class],
                    "process_residue_odt": residue,
                    "reference_process_residue_odt": chain.class_residue_odt[
                        facility_class
                    ],
                    "process_residue_gap_odt": (
                        residue - chain.class_residue_odt[facility_class]
                    ),
                    "facility_count": len(facility_ids),
                    "local_feedstock_m3": local,
                    "cross_border_feedstock_m3": facility_feedstock - local,
                    "proxy_feedstock_m3": proxy,
                    "fallback_feedstock_m3": fallback,
                    "allocation_scopes": ";".join(scopes) if scopes else "zero",
                    "coefficient_tier": chain.coefficient_tier,
                    "product_per_m3": (
                        chain.class_product[facility_class] / reference_feedstock
                        if reference_feedstock > 0.0
                        else 0.0
                    ),
                    "residue_odt_per_m3": (
                        chain.class_residue_odt[facility_class] / reference_feedstock
                        if reference_feedstock > 0.0
                        else 0.0
                    ),
                    "model_estimate": LABEL_TRUE,
                    "observed": LABEL_FALSE,
                    "policy_grade": LABEL_FALSE,
                    "facility_assignment": LABEL_TRUE,
                }
            )
    return rows


def _concentration(
    facility_totals: Mapping[str, float],
    facility_meta: Mapping[str, FacilityAllocation],
) -> dict[str, Any]:
    total = math.fsum(facility_totals.values())
    if total <= 0.0:
        raise FacilityProductChainError("facility feedstock total is zero")
    ordered = sorted(facility_totals.items(), key=lambda item: item[1], reverse=True)
    shares = [value / total for _, value in ordered]
    hhi = math.fsum(share * share for share in shares)
    top1 = shares[0]
    top5 = math.fsum(shares[:5])
    proxy_feedstock = math.fsum(
        value
        for facility_id, value in facility_totals.items()
        if facility_meta[facility_id].capacity_status == "proxy"
    )
    proxy_facilities = sum(
        1
        for facility_id in facility_totals
        if facility_meta[facility_id].capacity_status == "proxy"
    )
    published_facilities = len(facility_totals) - proxy_facilities
    used_capacity = math.fsum(
        facility_meta[facility_id].capacity_m3_y for facility_id in facility_totals
    )
    proxy_capacity = math.fsum(
        facility_meta[facility_id].capacity_m3_y
        for facility_id in facility_totals
        if facility_meta[facility_id].capacity_status == "proxy"
    )
    class_summary: dict[str, Any] = {}
    for facility_class in CLASS_ORDER:
        class_total = math.fsum(
            value
            for facility_id, value in facility_totals.items()
            if facility_meta[facility_id].facility_class == facility_class
        )
        class_proxy = math.fsum(
            value
            for facility_id, value in facility_totals.items()
            if facility_meta[facility_id].facility_class == facility_class
            and facility_meta[facility_id].capacity_status == "proxy"
        )
        class_capacity = math.fsum(
            facility_meta[facility_id].capacity_m3_y
            for facility_id in facility_totals
            if facility_meta[facility_id].facility_class == facility_class
        )
        class_proxy_capacity = math.fsum(
            facility_meta[facility_id].capacity_m3_y
            for facility_id in facility_totals
            if facility_meta[facility_id].facility_class == facility_class
            and facility_meta[facility_id].capacity_status == "proxy"
        )
        class_summary[facility_class] = {
            "feedstock_m3": class_total,
            "share_of_facility_feedstock": class_total / total,
            "proxy_feedstock_m3": class_proxy,
            "proxy_feedstock_share": (
                class_proxy / class_total if class_total > 0.0 else 0.0
            ),
            "facilities_used": sum(
                1
                for facility_id in facility_totals
                if facility_meta[facility_id].facility_class == facility_class
            ),
            "proxy_capacity_share": (
                class_proxy_capacity / class_capacity
                if class_capacity > 0.0
                else 0.0
            ),
        }
    return {
        "facilities_used": len(facility_totals),
        "feedstock_m3": total,
        "hhi": hhi,
        "effective_facility_count": 1.0 / hhi if hhi > 0.0 else 0.0,
        "top1_share": top1,
        "top5_share": top5,
        "proxy_facility_count": proxy_facilities,
        "published_facility_count": published_facilities,
        "proxy_facility_share": proxy_facilities / len(facility_totals),
        "proxy_feedstock_m3": proxy_feedstock,
        "proxy_feedstock_share_of_total": proxy_feedstock / total,
        "published_feedstock_m3": total - proxy_feedstock,
        "proxy_capacity_m3_y": proxy_capacity,
        "used_facility_capacity_m3_y": used_capacity,
        "proxy_capacity_share_of_used_facility_capacity": (
            proxy_capacity / used_capacity if used_capacity > 0.0 else 0.0
        ),
        "by_class": class_summary,
    }


def _top_facilities(
    facility_totals: Mapping[str, float],
    facility_meta: Mapping[str, FacilityAllocation],
    allocations: Sequence[FacilityAllocation],
    limit: int = 20,
) -> list[dict[str, Any]]:
    total = math.fsum(facility_totals.values())
    ordered = sorted(facility_totals.items(), key=lambda item: item[1], reverse=True)
    origin_counts: dict[str, set[str]] = defaultdict(set)
    process_residue: dict[str, float] = defaultdict(float)
    for allocation in allocations:
        origin_counts[allocation.facility_id].add(allocation.origin_province)
        process_residue[allocation.facility_id] += allocation.process_residue_odt
    rows: list[dict[str, Any]] = []
    cumulative = 0.0
    for rank, (facility_id, feedstock) in enumerate(ordered[:limit], start=1):
        share = feedstock / total
        cumulative += share
        meta = facility_meta[facility_id]
        rows.append(
            {
                "rank": rank,
                "facility_id": facility_id,
                "facility_name": meta.facility_name,
                "facility_class": meta.facility_class,
                "facility_province": meta.facility_province,
                "capacity_status": meta.capacity_status,
                "capacity_m3_y": meta.capacity_m3_y,
                "feedstock_m3": feedstock,
                "share_of_facility_feedstock": share,
                "cumulative_share": cumulative,
                "process_residue_odt": process_residue[facility_id],
                "origin_province_count": len(origin_counts[facility_id]),
            }
        )
    return rows


def _national_totals(
    province_rows: Sequence[Mapping[str, Any]],
    concentration: Mapping[str, Any],
) -> dict[str, float]:
    totals: dict[str, float] = {}
    additive_keys = [
        "harvest_m3",
        "primary_feedstock_m3",
        "residue_feedstock_m3",
        "total_feedstock_m3",
        *CLASS_FEEDSTOCK_COLUMN.values(),
        *CLASS_PRODUCT_COLUMN.values(),
        *CLASS_RESIDUE_COLUMN.values(),
        "process_residue_odt",
        "process_residue_m3",
        "harvest_residue_gross_m3",
        "harvest_residue_gross_odt",
        "harvest_residue_recoverable_m3",
        "harvest_residue_recoverable_odt",
        "harvest_residue_unrecovered_m3",
        "harvest_residue_unrecovered_odt",
        "total_residue_gross_odt",
        "total_residue_recoverable_odt",
        "rsyc_base_recoverable_odt",
        "model_recoverable_odt_base",
        "facility_feedstock_m3",
        "local_feedstock_m3",
        "cross_border_feedstock_m3",
        "proxy_feedstock_m3",
        "fallback_feedstock_m3",
    ]
    for key in additive_keys:
        totals[key] = math.fsum(float(row[key]) for row in province_rows)
    totals["process_residue_odt_per_m3_feedstock"] = (
        totals["process_residue_odt"] / totals["total_feedstock_m3"]
        if totals["total_feedstock_m3"] > 0.0
        else 0.0
    )
    totals["facilities_used"] = float(concentration["facilities_used"])
    totals["hhi"] = float(concentration["hhi"])
    totals["top1_share"] = float(concentration["top1_share"])
    totals["top5_share"] = float(concentration["top5_share"])
    totals["proxy_feedstock_share_of_total"] = float(
        concentration["proxy_feedstock_share_of_total"]
    )
    totals["proxy_capacity_share_of_used_facility_capacity"] = float(
        concentration["proxy_capacity_share_of_used_facility_capacity"]
    )
    totals["cross_border_feedstock_share"] = (
        totals["cross_border_feedstock_m3"] / totals["total_feedstock_m3"]
        if totals["total_feedstock_m3"] > 0.0
        else 0.0
    )
    totals["fallback_feedstock_share"] = (
        totals["fallback_feedstock_m3"] / totals["total_feedstock_m3"]
        if totals["total_feedstock_m3"] > 0.0
        else 0.0
    )
    totals["rsyc_ratio"] = (
        totals["model_recoverable_odt_base"] / totals["rsyc_base_recoverable_odt"]
        if totals["rsyc_base_recoverable_odt"] > 0.0
        else 0.0
    )
    totals["rsyc_status"] = _rsyc_status(
        totals["rsyc_ratio"], totals["harvest_m3"]
    )
    return totals


def _check(
    checks: list[dict[str, Any]],
    check_id: str,
    passed: bool,
    detail: str,
    **metrics: Any,
) -> None:
    checks.append(
        {
            "check_id": check_id,
            "status": "PASS" if passed else "FAIL",
            "detail": detail,
            **metrics,
        }
    )
    if not passed:
        raise FacilityProductChainError(f"{check_id}: {detail}")


def _validate(
    chains: Mapping[str, ProvinceChain],
    allocations: Sequence[FacilityAllocation],
    province_rows: Sequence[Mapping[str, Any]],
    class_rows: Sequence[Mapping[str, Any]],
    facility_totals: Mapping[str, float],
    facility_meta: Mapping[str, FacilityAllocation],
    totals: Mapping[str, float],
    rsyc_factors: Mapping[str, float],
    product_chain_summary: Mapping[str, Any],
    assignment_summary: Mapping[str, Any],
    deletion_clean: bool,
) -> list[dict[str, Any]]:
    checks: list[dict[str, Any]] = []

    # 1. Class matching and class-safe pools.
    mixed: list[str] = []
    facility_classes: dict[str, str] = {}
    for allocation in allocations:
        if (
            allocation.facility_class not in CLASS_ORDER
            or allocation.feedstock_class != allocation.facility_class
        ):
            mixed.append(allocation.facility_id)
        previous_class = facility_classes.get(allocation.facility_id)
        if previous_class is not None and previous_class != allocation.facility_class:
            mixed.append(f"{allocation.facility_id}: multiple classes")
        facility_classes[allocation.facility_id] = allocation.facility_class
    _check(
        checks,
        "class_matching",
        not mixed,
        f"{len(mixed)} class-mismatched allocation rows",
        allocation_rows=len(allocations),
    )

    # 2. Province/class feedstock conservation.
    feedstock_gaps: list[tuple[str, str, float]] = []
    for row in class_rows:
        gap = float(row["feedstock_gap_m3"])
        scale = max(float(row["feedstock_m3"]), 1.0)
        if abs(gap) > REL_TOL * scale:
            feedstock_gaps.append(
                (str(row["province"]), str(row["facility_class"]), gap)
            )
    _check(
        checks,
        "province_class_feedstock_conservation",
        not feedstock_gaps,
        f"{len(feedstock_gaps)} province/class feedstock gaps exceed tolerance",
        max_abs_gap_m3=max(
            (abs(float(row["feedstock_gap_m3"])) for row in class_rows),
            default=0.0,
        ),
        tolerance_relative=REL_TOL,
    )

    # 3. National class feedstock and product/residue conservation.
    for facility_class in CLASS_ORDER:
        column = CLASS_FEEDSTOCK_COLUMN[facility_class]
        reference = math.fsum(
            chain.class_feedstock_m3[facility_class]
            for chain in chains.values()
        )
        _require_close(totals[column], reference, f"national {facility_class} feedstock")
        product_column = CLASS_PRODUCT_COLUMN[facility_class]
        product_reference = math.fsum(
            chain.class_product[facility_class] for chain in chains.values()
        )
        _require_close(
            totals[product_column],
            product_reference,
            f"national {facility_class} product",
        )
        residue_column = CLASS_RESIDUE_COLUMN[facility_class]
        residue_reference = math.fsum(
            chain.class_residue_odt[facility_class] for chain in chains.values()
        )
        _require_close(
            totals[residue_column],
            residue_reference,
            f"national {facility_class} process residue",
        )
    _check(
        checks,
        "national_product_residue_conservation",
        True,
        "all five class products and process residues match product-chain totals",
    )

    # 4. Cross-check against the product-chain summary national totals.
    product_chain_national = product_chain_summary.get("national_totals", {})
    for key in (
        "total_feedstock_m3",
        "pulp_product_odt",
        "sawlog_product_m3",
        "panel_product_m3",
        "pellet_product_odt",
        "bio_product_mwh",
        "process_residue_odt",
        "harvest_residue_gross_odt",
        "harvest_residue_recoverable_odt",
        "rsyc_base_recoverable_odt",
        "model_recoverable_odt_base",
    ):
        if key not in product_chain_national:
            continue
        expected = float(product_chain_national[key])
        actual = float(totals[key])
        _require_close(actual, expected, f"product-chain summary {key}")
    _check(
        checks,
        "product_chain_summary_crosscheck",
        True,
        "facility totals reproduce product-chain summary national totals",
    )

    # 5. No negative or non-finite quantities.
    invalid: list[str] = []
    for allocation in allocations:
        for field in (
            "assignment_weight_m3",
            "assignment_share",
            "capacity_m3_y",
            "utilization",
            "feedstock_m3",
            "product_quantity",
            "process_residue_odt",
            "process_residue_m3",
            "product_per_m3",
            "residue_odt_per_m3",
        ):
            value = float(getattr(allocation, field))
            if not math.isfinite(value) or value < 0.0:
                invalid.append(f"{allocation.facility_id}.{field}")
    for row in province_rows:
        for key, value in row.items():
            if isinstance(value, float) and (
                not math.isfinite(value) or value < 0.0
            ):
                invalid.append(f"{row['province']}.{key}")
    _check(
        checks,
        "finite_nonnegative",
        not invalid,
        f"{len(invalid)} non-finite or negative values",
    )

    # 6. Allocation shares are normalized within every origin/class pool.
    share_errors: list[str] = []
    grouped_shares: dict[tuple[str, str], float] = defaultdict(float)
    grouped_feedstock: dict[tuple[str, str], float] = defaultdict(float)
    for allocation in allocations:
        key = (allocation.origin_province, allocation.facility_class)
        grouped_shares[key] += allocation.assignment_share
        grouped_feedstock[key] += allocation.feedstock_m3
    for (province, facility_class), share in grouped_shares.items():
        if abs(share - 1.0) > REL_TOL:
            share_errors.append(f"{province}/{facility_class}={share:.12f}")
        reference = chains[province].class_feedstock_m3[facility_class]
        if abs(grouped_feedstock[(province, facility_class)] - reference) > (
            REL_TOL * max(reference, 1.0)
        ):
            share_errors.append(f"{province}/{facility_class} feedstock")
    _check(
        checks,
        "allocation_normalization",
        not share_errors,
        f"failed pools: {share_errors[:5]}",
    )

    # 7. Class fallback is explicit and local-first.
    fallback_errors: list[str] = []
    for row in class_rows:
        if row["allocation_scopes"] == "national_class_fallback":
            continue
        if row["allocation_scopes"] == "zero" and float(row["feedstock_m3"]) <= 0.0:
            continue
        if "national_class_fallback" in str(row["allocation_scopes"]):
            fallback_errors.append(
                f"{row['province']}/{row['facility_class']}: mixed scopes"
            )
    _check(
        checks,
        "fallback_scope",
        not fallback_errors,
        f"failed: {fallback_errors}",
        fallback_feedstock_m3=totals["fallback_feedstock_m3"],
    )

    # 8. Harvest residue is separate from facility process residue.
    harvest_errors: list[str] = []
    for row in province_rows:
        process = float(row["process_residue_odt"])
        harvest = float(row["harvest_residue_gross_odt"])
        if abs(float(row["total_residue_gross_odt"]) - (process + harvest)) > (
            REL_TOL * max(process + harvest, 1.0)
        ):
            harvest_errors.append(str(row["province"]))
    for row in province_rows:
        if row["harvest_residue_scope"] != "province_only":
            harvest_errors.append(str(row["province"]))
    _check(
        checks,
        "harvest_residue_separate",
        not harvest_errors,
        f"failed: {harvest_errors}",
    )

    # 9. RSYC base and model reproduction.
    rsyc_errors: list[str] = []
    for province, chain in chains.items():
        if chain.harvest_m3 <= 0.0:
            continue
        base = chain.harvest_m3 * rsyc_factors[province]
        if abs(base - chain.rsyc_base_recoverable_odt) > (
            REL_TOL * max(base, 1.0)
        ):
            rsyc_errors.append(province)
    national_ratio = (
        totals["model_recoverable_odt_base"] / totals["rsyc_base_recoverable_odt"]
        if totals["rsyc_base_recoverable_odt"] > 0.0
        else 0.0
    )
    expected_ratio = float(
        product_chain_summary.get("rsyc_comparison", {}).get("ratio", national_ratio)
    )
    if abs(national_ratio - expected_ratio) > REL_TOL * max(expected_ratio, 1.0):
        rsyc_errors.append("national ratio")
    _check(
        checks,
        "rsyc_reproduction",
        not rsyc_errors,
        f"failed: {rsyc_errors}",
        national_rsyc_ratio=national_ratio,
    )

    # 10. Proxy capacity metadata is present for every used facility.
    capacity_errors = [
        facility_id
        for facility_id in facility_totals
        if facility_meta[facility_id].capacity_status not in {"published", "proxy"}
        or facility_meta[facility_id].capacity_m3_y <= 0.0
    ]
    _check(
        checks,
        "used_facility_capacity",
        not capacity_errors,
        f"failed: {capacity_errors[:5]}",
    )

    # 11. Assignment-v2 scenario labels and proxy share are retained.
    scenario = assignment_summary["scenarios"][SCENARIO]
    assignment_errors: list[str] = []
    if float(scenario.get("unassigned_m3", 0.0)) != 0.0:
        assignment_errors.append("scenario has unassigned volume")
    if float(scenario.get("assigned_m3", 0.0)) <= 0.0:
        assignment_errors.append("scenario assigned volume is zero")
    _check(
        checks,
        "assignment_scenario",
        not assignment_errors,
        f"failed: {assignment_errors}",
    )

    # 12. Repository hygiene gate.
    _check(
        checks,
        "repository_hygiene",
        deletion_clean,
        "no unexpected D in parent or data git status" if deletion_clean
        else "unexpected deletion status",
    )
    return checks


